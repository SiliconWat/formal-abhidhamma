#!/usr/bin/env python3
"""sampayoga_matrix.py — BLIND data for run 2026-11-22-dhatukatha-association-3: the Dhātukathā's sixth method, its matrix triads (§5, Tikaṃ), for the ten classes of
Classes.lean. Writes dhatukatha/SampayogaMatrix.lean and PRINTS NO COUNT — only how many rows each class matched — so the stated numbers are not seen before the
comparison (the run's registration fixes the rule first).   sampayoga_matrix.py --check exits 1 if the file is stale.
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(REPO, "scripts"))
import dhatukatha as D
import dhatukatha_all as A

CLASSES = {"sukhāya vedanāya sampayuttā dhammā": "sukha_sampayutta", "dukkhāya vedanāya sampayuttā dhammā": "dukkha_sampayutta",
           "adukkhamasukhāya vedanāya sampayuttā dhammā": "adukkhamasukha_sampayutta", "pītisahagatā dhammā": "piti_sahagata",
           "sukhasahagatā dhammā": "sukha_sahagata", "upekkhāsahagatā dhammā": "upekkha_sahagata", "vipākā dhammā": "vipaka",
           "mahaggatā dhammā": "mahaggata", "sanidassanasappaṭighā dhammā": "sanidassana_sappatigha", "anidassanasappaṭighā dhammā": "anidassana_sappatigha"}


def parse():
    ls = D.server.lines("abh03m1.mul.xml")
    clean = lambda l: re.sub(r"\s+", " ", D.server.plain(l)).strip()
    start = next(i for i, l in enumerate(ls, 1) if clean(l) == "6. Chaṭṭhanayo")
    end = next(i for i, l in enumerate(ls, 1) if clean(l) == "7. Sattamanayo")
    rows, unmatched, in_tika = [], 0, False
    for i in range(start, end):
        raw, t = ls[i - 1], clean(ls[i - 1])
        if 'rend="subhead"' in raw:
            in_tika = bool(re.match(r"\d+\.\s*Tikaṃ", t)); continue
        m = re.match(r"^(\d+)\. (.*)$", t)
        if not in_tika or not m:
            continue
        body = m.group(2)
        cut = re.search(r"\bkatihi\b|\b(?:na kehici|eken\w*|ekāya|dvīh\w*|tīh\w*|catūh\w*|pañcah\w*|chah\w*|sattah\w*|aṭṭhah\w*|navah\w*|dasah\w*|ekādasah\w*|dvādasah\w*|soḷasah\w*|sattarasah\w*|aṭṭhārasah\w*)\s", body)
        subj = body[:cut.start()] if cut else body
        slugs = []
        for piece in re.split(r"\s*…(?:pe…)?\s*", subj):
            key = re.sub(r"\s+", " ", D.norm(piece).strip(" ,.;"))
            if key in CLASSES:
                slugs.append(CLASSES[key])
            elif key:
                unmatched += 1
        if not slugs:
            continue
        tr = A.triples(t)
        pick = lambda verb, part: next((a[1] for a in tr if a[0] == verb and a[2] == part), None)
        z = lambda x: tuple(0 if v is None else v for v in x) if x else (0, 0, 0)
        aF, aP, dF, dP = pick("sampayutt", False), pick("sampayutt", True), pick("vippayutt", False), pick("vippayutt", True)
        assoc_none = bool(re.search(r"sampayutt\w*\?\s*Natthi", t)); dissoc_none = bool(re.search(r"vippayutt\w*\?\s*Natthi", t))
        if (aF is None and aP is None and not assoc_none) or (dF is None and dP is None and not dissoc_none):
            continue
        for s in slugs:
            rows.append(dict(line=i, items=[s], aF=z(aF), aP=z(aP), dF=z(dF), dP=z(dP)))
    return rows, unmatched


def lean(rows):
    out = ["/-", "  dhatukatha/SampayogaMatrix.lean — GENERATED by sampayoga_matrix.py (⛔ never edited by hand): the sixth method's matrix triads (§5), for the ten classes of",
           "  Classes.lean. BLIND data of run 2026-11-22-dhatukatha-association-3: written without being displayed, the rule registered first.", "-/",
           "import Sampayoga", "namespace FormalAbhidhamma.Dhatukatha", "", "def mrows : List SRow := ["]
    out.append(",\n".join("  ⟨%d, [%s], (%d, %d, %d), (%d, %d, %d), (%d, %d, %d), (%d, %d, %d)⟩" % (r["line"], ", ".join(f'"{x}"' for x in r["items"]), *r["aF"], *r["aP"], *r["dF"], *r["dP"]) for r in rows))
    out += ["]", "", "end FormalAbhidhamma.Dhatukatha"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    rows, unmatched = parse(); text = lean(rows); p = os.path.join(HERE, "SampayogaMatrix.lean")
    if sys.argv[1:] == ["--check"]:
        ok = os.path.exists(p) and open(p, encoding="utf-8").read() == text
        print("SampayogaMatrix.lean is current" if ok else "STALE: SampayogaMatrix.lean"); sys.exit(0 if ok else 1)
    open(p, "w", encoding="utf-8").write(text)
    from collections import Counter
    print("rows matched per class (counts NOT shown):", dict(Counter(r["items"][0] for r in rows)), "· subject pieces outside the ten classes:", unmatched)
