#!/usr/bin/env python3
"""classes.py — for run 2026-11-22-dhatukatha-association-3 (BLIND): ten matrix classes, each with its COMPOSITION as the Dhammasaṅgaṇī defines it (its Nikkhepa,
abh01m.mul.xml:7029–7185) and its consciousness ELEMENTS from the Dhammasaṅgaṇī's Cittuppāda (cittuppada/CITTUPPADA.json, through ranges.py's reading rules).
Fixed and committed BEFORE the run is registered, and before any of the sixth method's matrix rows is read. Writes dhatukatha/Classes.lean.

  composition, from the definitions:
    feeling set aside    — "sukhaṃ vedanaṃ ṭhapetvā; taṃsampayutto saññākkhandho, saṅkhārakkhandho, viññāṇakkhandho" (:7029, :7033, the third alike; :7093, :7097)
    rapture set aside    — "pītiṃ ṭhapetvā; taṃsampayutto vedanākkhandho…pe… viññāṇakkhandho" (:7089)
    all four aggregates  — "vedanākkhandho…pe… viññāṇakkhandho" (vipākā :7041, mahaggatā :7185)
    matter               — the visible and the other impinging forms (the matrix's last triad)
  elements: a feeling class from the faculty terms of its feelings (Ranges); a "-sahagatā" class from the term set aside (pīti, sukhaṃ, upekkhā); vipākā from every
  Cittuppāda class described as a result; mahaggatā from every class of the fine-material and immaterial spheres.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import ranges as R


def class_elements(pred):
    """The elements of every Cittuppāda class whose feature words satisfy pred (ranges.py's reading of several-consciousness sentences)."""
    d = json.load(open(os.path.join(REPO, "cittuppada", "CITTUPPADA.json"), encoding="utf-8"))
    out = set()
    for c in d["classes"]:
        words = [w.strip(",").lower() for w in c["features"]]
        if not pred(words):
            continue
        named = [e for w in words for k, e in R.SENSE if w.startswith(k)]
        if named:
            out |= set(named)
        elif "manodhātu" in words:
            out.add("manoD")
        else:
            out.add("manoV")
    return out


def table():
    E = R.element_sets()
    t = lambda *terms: set().union(*(E.get(x, set()) for x in terms))
    return [
        ("sukha_sampayutta", "feelingAside", t("sukhindriyaṃ", "somanassindriyaṃ")),
        ("dukkha_sampayutta", "feelingAside", t("dukkhindriyaṃ", "domanassindriyaṃ")),
        ("adukkhamasukha_sampayutta", "feelingAside", t("upekkhindriyaṃ")),
        ("piti_sahagata", "formationAside", t("pīti")),
        ("sukha_sahagata", "feelingAside", t("sukhaṃ")),
        ("upekkha_sahagata", "feelingAside", t("upekkhā")),
        ("vipaka", "allFour", class_elements(lambda w: any(x.startswith("vipāk") for x in w))),
        ("mahaggata", "allFour", class_elements(lambda w: any(x.startswith(("rūpāvacar", "arūpāvacar")) for x in w))),
        ("sanidassana_sappatigha", "matter", set()),
        ("anidassana_sappatigha", "matter", set()),
    ]


def lean(rows):
    out = ["/-", "  dhatukatha/Classes.lean — GENERATED by classes.py (⛔ never edited by hand): ten matrix classes, their composition (the Dhammasaṅgaṇī's Nikkhepa) and",
           "  consciousness elements (its Cittuppāda: 0 eye · 1 ear · 2 nose · 3 tongue · 4 body · 5 mind-element · 6 mind-consciousness), fixed before run",
           "  2026-11-22-dhatukatha-association-3 is registered and before any of the sixth method's matrix rows is read.", "-/", "namespace FormalAbhidhamma.Dhatukatha", "",
           "def classes : List (String × String × List Nat) := ["]
    out.append(",\n".join(f'  ("{s}", "{k}", [{", ".join(str(R.ORDER.index(e)) for e in sorted(E, key=R.ORDER.index))}])' for s, k, E in rows))
    out += ["]", "", "end FormalAbhidhamma.Dhatukatha"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    rows = table(); text = lean(rows); p = os.path.join(HERE, "Classes.lean")
    if sys.argv[1:] == ["--check"]:
        ok = os.path.exists(p) and open(p, encoding="utf-8").read() == text
        print("Classes.lean is current" if ok else "STALE: Classes.lean"); sys.exit(0 if ok else 1)
    open(p, "w", encoding="utf-8").write(text)
    for s, k, E in rows:
        print(f"{s:28} {k:15} {sorted(E, key=R.ORDER.index)}")
