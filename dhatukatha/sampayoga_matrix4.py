#!/usr/bin/env python3
"""sampayoga_matrix4.py — BLIND data for run 2026-11-22-dhatukatha-association-4: the Dhātukathā's sixth method, its matrix triads (§5, Tikaṃ), for the classes of
Classes4.lean (the scope classes4.py reads from the Nikkhepa). Writes dhatukatha/SampayogaMatrix4.lean and PRINTS NO COUNT — only how many rows each class matched — so
the stated numbers are not seen before the comparison (the run's registration fixes the rule and the predictions first). Same row reading as sampayoga_matrix.py (run 3),
with the name split of classes4.py (several names joined in one piece; one-word "-dhammadhammā" names).
  sampayoga_matrix4.py --check exits 1 if the file is stale.
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(REPO, "scripts"))
import dhatukatha as D
import dhatukatha_all as A
import classes4 as C4


def parse():
    rows4, _, _ = C4.table()
    want = {(line, name) for line, name, _, _ in rows4}
    ls = D.server.lines("abh03m1.mul.xml")
    clean = lambda l: re.sub(r"\s+", " ", D.server.plain(l)).strip()
    rows = []
    for line, names in C4.matrix_names():
        hits = [n for n in names if (line, n) in want]
        if not hits:
            continue
        t = clean(ls[line - 1])
        tr = A.triples(t)
        pick = lambda verb, part: next((a[1] for a in tr if a[0] == verb and a[2] == part), None)
        z = lambda x: tuple(0 if v is None else v for v in x) if x else (0, 0, 0)
        aF, aP, dF, dP = pick("sampayutt", False), pick("sampayutt", True), pick("vippayutt", False), pick("vippayutt", True)
        assoc_none = bool(re.search(r"sampayutt\w*\?\s*Natthi", t)); dissoc_none = bool(re.search(r"vippayutt\w*\?\s*Natthi", t))
        if (aF is None and aP is None and not assoc_none) or (dF is None and dP is None and not dissoc_none):
            continue
        for n in hits:
            rows.append(dict(line=line, items=[C4.slug(n)], aF=z(aF), aP=z(aP), dF=z(dF), dP=z(dP)))
    return rows, len(want)


def lean(rows):
    out = ["/-", "  dhatukatha/SampayogaMatrix4.lean — GENERATED by sampayoga_matrix4.py (⛔ never edited by hand): the sixth method's matrix triads (§5) for the classes of",
           "  Classes4.lean. BLIND data of run 2026-11-22-dhatukatha-association-4: written without being displayed, the rule and predictions registered first.", "-/",
           "import Sampayoga", "namespace FormalAbhidhamma.Dhatukatha", "", "def mrows4 : List SRow := ["]
    out.append(",\n".join("  ⟨%d, [%s], (%d, %d, %d), (%d, %d, %d), (%d, %d, %d), (%d, %d, %d)⟩" % (r["line"], ", ".join(f'"{x}"' for x in r["items"]), *r["aF"], *r["aP"], *r["dF"], *r["dP"]) for r in rows))
    out += ["]", "", "end FormalAbhidhamma.Dhatukatha"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    rows, wanted = parse(); text = lean(rows); p = os.path.join(HERE, "SampayogaMatrix4.lean")
    if sys.argv[1:] == ["--check"]:
        ok = os.path.exists(p) and open(p, encoding="utf-8").read() == text
        print("SampayogaMatrix4.lean is current" if ok else "STALE: SampayogaMatrix4.lean"); sys.exit(0 if ok else 1)
    open(p, "w", encoding="utf-8").write(text)
    print(f"rows written (counts NOT shown): {len(rows)} of {wanted} classes in scope; lines: {sorted({r['line'] for r in rows})}")
