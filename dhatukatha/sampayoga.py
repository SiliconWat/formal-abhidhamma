#!/usr/bin/env python3
"""sampayoga.py — the Dhātukathā's SIXTH method (sampayoga-vippayoga), its inner list (§1–4, the first method's §1–6), as Lean data: each item (read by dhatukatha.py's own
match_items, so an item means what it meant in the first method) and its stated association and dissociation counts, full and partial
(read by scripts/dhatukatha_all.py's triples). Pre-registered: runs/2026-11-22-dhatukatha-association/PREREG.md. The counts are the TEST
BANK, never premises.   sampayoga.py --check exits 1 if the generated files are stale.
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(REPO, "scripts"))
import dhatukatha as D          # match_items, norm, server (the CST reader)
import dhatukatha_all as A      # triples

FILE = "abh03m1.mul.xml"


def parse():
    ls = D.server.lines(FILE)
    clean = lambda l: re.sub(r"\s+", " ", D.server.plain(l)).strip()
    start = next(i for i, l in enumerate(ls, 1) if clean(l) == "6. Chaṭṭhanayo")
    end = next(i for i, l in enumerate(ls, 1) if clean(l) == "7. Sattamanayo")
    rows, skipped, section = [], [], None
    for i in range(start, end):
        raw, t = ls[i - 1], clean(ls[i - 1])
        if 'rend="subhead"' in raw:
            m = re.match(r"(\d+)\.", t); section = int(m.group(1)) if m else None
            continue
        m = re.match(r"^(\d+)\. (.*)$", t)
        # the inner list is this method's §1–4 (Khandho, Āyatanaṃ, Dhātu, Saccādi — truths, faculties, dependent origination): the same items
        # the first method numbers §1–6; from §5 (Tikaṃ) the matrix, whose items have no dhamma sets in Check.lean
        if not m or section is None or section > 4:
            continue
        body = m.group(2)
        # the subjects: everything before the question word or the first count; alternatives separated by "…"
        cut = re.search(r"\bkatihi\b|\b(?:na kehici|eken\w*|ekāya|dvīh\w*|tīh\w*|catūh\w*|pañcah\w*|chah\w*|sattah\w*|aṭṭhah\w*|navah\w*|dasah\w*|ekādasah\w*|dvādasah\w*|soḷasah\w*|sattarasah\w*|aṭṭhārasah\w*)\s", body)
        subj = body[:cut.start()] if cut else body
        subsets = []
        for piece in re.split(r"\s*…(?:pe…)?\s*", subj):
            items, rest = D.match_items(piece.split())
            if items and not [x for x in rest if D.norm(x) not in ("ca",)]:
                subsets.append(items)
        tr = A.triples(t)
        if not subsets or (not tr and "Natthi" not in t):
            skipped.append((i, "no items" if not subsets else "no answers")); continue
        pick = lambda verb, part: next((a[1] for a in tr if a[0] == verb and a[2] == part), None)
        z = lambda x: tuple(0 if v is None else v for v in x) if x else (0, 0, 0)
        aF, aP, dF, dP = pick("sampayutt", False), pick("sampayutt", True), pick("vippayutt", False), pick("vippayutt", True)
        if aF is None and aP is None and not re.search(r"sampayutt\w*\?\s*Natthi", t):
            skipped.append((i, "association unstated")); continue
        if dF is None and dP is None and not re.search(r"vippayutt\w*\?\s*Natthi", t):
            skipped.append((i, "dissociation unstated")); continue
        for s in subsets:
            rows.append(dict(line=i, section=section, items=s, aF=z(aF), aP=z(aP), dF=z(dF), dP=z(dP)))
    return rows, skipped


def lean(rows):
    out = ["/-", "  dhatukatha/Sampayoga.lean — GENERATED by sampayoga.py (⛔ never edited by hand): the Dhātukathā's sixth method, its inner list (§1–4), as data.",
           "  The COUNTS are the test bank (pre-registered: runs/2026-11-22-dhatukatha-association/PREREG.md); CheckSampayoga.lean computes them.", "-/",
           "namespace FormalAbhidhamma.Dhatukatha", "",
           "/-- One stated row: the items, and the numbers of aggregates, bases and elements it is associated with fully (aF) and partially, *kehici* (aP), and dissociated from (dF, dP). -/",
           "structure SRow where\n  line : Nat\n  items : List String\n  aF : Nat × Nat × Nat\n  aP : Nat × Nat × Nat\n  dF : Nat × Nat × Nat\n  dP : Nat × Nat × Nat\n  deriving Repr\n",
           "def srows : List SRow := ["]
    out.append(",\n".join("  ⟨%d, [%s], (%d, %d, %d), (%d, %d, %d), (%d, %d, %d), (%d, %d, %d)⟩" % (r["line"], ", ".join(f'"{x}"' for x in r["items"]), *r["aF"], *r["aP"], *r["dF"], *r["dP"]) for r in rows))
    out.append("]\n\nend FormalAbhidhamma.Dhatukatha")
    return "\n".join(out) + "\n"


def md(rows, skipped):
    L = ["# SAMPAYOGA — the Dhātukathā's sixth method, its inner list (§1–4), as captured", "",
         "*GENERATED by `sampayoga.py` from `abh03m1.mul.xml` (the Chaṭṭhanayo). ⛔ Never edited by hand. The counts are the TEST BANK, never premises; pre-registered in `runs/2026-11-22-dhatukatha-association/`.*", "",
         f"**{len(rows)} rows** (an item with its association and dissociation counts, full and partial). Skipped lines: {len(skipped)}.", ""]
    L += [f"- line {i}: {why}" for i, why in skipped]
    L += ["", "| line | items | associated (full) | associated (partial) | dissociated (full) | dissociated (partial) |", "|---|---|---|---|---|---|"]
    L += [f"| {r['line']} | {', '.join(r['items'])} | {r['aF']} | {r['aP']} | {r['dF']} | {r['dP']} |" for r in rows]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    rows, skipped = parse()
    texts = {os.path.join(HERE, "Sampayoga.lean"): lean(rows), os.path.join(HERE, "SAMPAYOGA.md"): md(rows, skipped)}
    if sys.argv[1:] == ["--check"]:
        bad = [p for p, t in texts.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        print("sampayoga files are current" if not bad else f"STALE: {bad}"); sys.exit(1 if bad else 0)
    for p, t in texts.items():
        open(p, "w", encoding="utf-8").write(t)
    print(f"{len(rows)} rows; skipped {len(skipped)}")
    for i, why in skipped:
        print("  skipped", i, why)
