#!/usr/bin/env python3
"""ranges.py — for each mental term of the Dhammasaṅgaṇī's Cittuppāda, the consciousness ELEMENTS it is listed with, read from cittuppada/CITTUPPADA.json
(generated from the CST by scripts/cittuppada.py). Written for run 2026-11-22-dhatukatha-association-2: the element ranges are the run's INDEPENDENT input —
taken from the Dhammasaṅgaṇī, never from the Dhātukathā's counts. Writes dhatukatha/Ranges.lean.   ranges.py --check exits 1 if it is stale.

READING RULES (declared in the pre-registration):
  · a class's element is its consciousness noun: a sense-consciousness (eye … body), the mind-element (manodhātu), else mind-consciousness;
  · a sentence naming several sense-consciousnesses, each before a …pe…, writes its list for the LAST named; each earlier one refers back to the
    eye-consciousness list of the same kind of result (kusala- or akusala-vipāka), with the feeling the sentence gives it;
  · a term is listed with an element when it is WRITTEN in a list of that element (presence only: absence from an elided list proves nothing).
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
SENSE = [("cakkhuviññāṇ", "eye"), ("sotaviññāṇ", "ear"), ("ghānaviññāṇ", "nose"), ("jivhāviññāṇ", "tongue"), ("kāyaviññāṇ", "body")]
ORDER = ["eye", "ear", "nose", "tongue", "body", "manoD", "manoV"]


def element_sets():
    d = json.load(open(os.path.join(REPO, "cittuppada", "CITTUPPADA.json"), encoding="utf-8"))
    E, eye_list = {}, {}
    for c in d["classes"]:
        words = [w.strip(",").lower() for w in c["features"]]
        named = [e for w in words for k, e in SENSE if w.startswith(k)]
        result = "kusala" if any(w.startswith("kusalass") for w in words) else ("akusala" if any(w.startswith("akusalass") for w in words) else None)
        if named:
            last = named[-1]
            if last == "eye" and result:
                eye_list[result] = c["padas"]
            # an earlier-named consciousness refers back (…pe…) to the eye list of the same result — or, where that eye is itself named before a …pe…
            # (the akusala-result sentence, abh01m.mul.xml:4441, names eye FIRST), to the parallel eye list of the other result (the refuter, run 2,
            # finding 5: the first version silently gave those an empty list; no count changed, the kusala sentences supplying the same elements)
            back = eye_list.get(result) or next(iter(eye_list.values()), [])
            groups = [(last, c["padas"])] + [(e, back) for e in named[:-1]]
        elif "manodhātu" in words:
            groups = [("manoD", c["padas"])]
        else:
            groups = [("manoV", c["padas"])]
        for e, ps in groups:
            for p in ps:
                E.setdefault(p, set()).add(e)
    return E


def lean(E):
    terms = sorted(E)
    out = ["/-", "  dhatukatha/Ranges.lean — GENERATED by ranges.py from cittuppada/CITTUPPADA.json (the Dhammasaṅgaṇī): for each term, the consciousness elements",
           "  it is WRITTEN with (0 eye · 1 ear · 2 nose · 3 tongue · 4 body · 5 mind-element · 6 mind-consciousness). The independent input of run",
           "  2026-11-22-dhatukatha-association-2. ⛔ Never edited by hand.", "-/", "namespace FormalAbhidhamma.Dhatukatha", "",
           "def ranges : List (String × List Nat) := ["]
    out.append(",\n".join(f'  ("{t}", [{", ".join(str(ORDER.index(e)) for e in sorted(E[t], key=ORDER.index))}])' for t in terms))
    out += ["]", "", "def rangeOf (t : String) : List Nat := ((ranges.find? (·.1 == t)).map (·.2)).getD []", "", "end FormalAbhidhamma.Dhatukatha"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    E = element_sets()
    text = lean(E)
    p = os.path.join(HERE, "Ranges.lean")
    if sys.argv[1:] == ["--check"]:
        ok = os.path.exists(p) and open(p, encoding="utf-8").read() == text
        print("Ranges.lean is current" if ok else "STALE: Ranges.lean"); sys.exit(0 if ok else 1)
    open(p, "w", encoding="utf-8").write(text)
    for t in ["phasso", "vedanā", "saññā", "cetanā", "cittaṃ", "sukhindriyaṃ", "dukkhindriyaṃ", "somanassindriyaṃ", "domanassindriyaṃ", "upekkhindriyaṃ",
              "saddhindriyaṃ", "vīriyindriyaṃ", "satindriyaṃ", "samādhindriyaṃ", "paññindriyaṃ", "manindriyaṃ", "anaññātaññassāmītindriyaṃ", "aññindriyaṃ", "aññātāvindriyaṃ"]:
        print(f"{t:28} {sorted(E.get(t, set()), key=ORDER.index)}")
