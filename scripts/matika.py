#!/usr/bin/env python3
"""matika.py — capture step 2 (founder 2026-10-13, "do the background items too"): the Dhammasaṅgaṇī's mātikā and the
Paṭṭhāna's 24 conditions as GENERATED data, never typed.

  scripts/matika.py            regenerate matika/MATIKA.md and matika/Matika.lean from the local CST text
  scripts/matika.py --check    exit 1 if either generated file differs from what the CST text gives now

Reads the LOCAL Chaṭṭha Saṅgāyana files (UTF-16; never in CI — the CST text is non-commercial, legal L21, so only
romanized canonical TERMS are written out, never running text: the rule of PREREGISTRATION-2026-09-27b.md §5). Each term's
CST line is kept. The edition's variant readings (a word followed by a siglum such as "(syā.)") are dropped.

What the Lean then checks against the TEXTS' OWN COUNTS (kala/ANSWERS.md rows "Dhs-a mātikā" and "Paṭṭh-a 24"):
22 triads of three, 100 Abhidhamma dyads of two, 42 Suttanta dyads (Atthasālinī `abh01a.att.xml:305`), and 24 conditions
(the Paṭṭhāna's uddesa). The method generator (6 methods × 4 directions = 24, Paṭṭhāna `abh03m7.mul.xml:449`, Paṭṭhāna-a
`abh03a.att.xml:7665`) is written in Matika.lean directly — it is structure, not text.
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CST = "/Users/siliconwat/Desktop/MA/SW/siliconwat.dev/bedok.siliconwat.dev/tipitaka/india/roman"
OUT_MD = os.path.join(REPO, "matika", "MATIKA.md")
OUT_LEAN = os.path.join(REPO, "matika", "Matika.lean")
SIGLUM = re.compile(r"\s+\S+\s+\((?:sī|syā|ka|pī|kaṃ|ṭī)[^)]*\)")

def lines(name):
    return open(os.path.join(CST, name), "rb").read().decode("utf-16").splitlines()

def plain(l):
    return re.sub(r"<[^>]+>", "", l).strip()

def clean(term):
    term = SIGLUM.sub("", term).strip().rstrip(".").strip()
    return re.sub(r"\s+", " ", term)

def matika():
    L, items, section, cur = lines("abh01m.mul.xml"), [], None, None
    start = next(i for i, l in enumerate(L) if plain(l) == "Mātikā")
    end = next(i for i, l in enumerate(L) if plain(l) == "Mātikā niṭṭhitā.")
    for i in range(start + 1, end):
        s, n = plain(L[i]), i + 1
        if not s: continue
        m = re.match(r"^(\d+)\.\s*\(Ka\)\s*(.+)$", s)
        if m:
            cur = {"section": section, "num": int(m.group(1)), "members": [(clean(m.group(2)), n)]}
            items.append(cur); continue
        m = re.match(r"^\((Kha|Ga)\)\s*(.+)$", s)
        if m and cur:
            cur["members"].append((clean(m.group(2)), n)); continue
        if s.endswith(".") or "niṭṭhitā" in s: continue
        section = re.sub(r"^\d+\.\s*", "", s)
    return items

def conditions():
    L = lines("abh03m7.mul.xml")
    for i, l in enumerate(L):
        s = plain(l)
        if s.startswith("Hetupaccayo, ārammaṇapaccayo"):
            names = [x.strip() for x in s.rstrip(".").replace("ti.", "").split(",")]
            names = [re.sub(r"(ti|’ti|'ti)$", "", x).strip() for x in names if x.strip()]
            return names, i + 1
    raise SystemExit("the Paṭṭhāna's uddesa line was not found — is the local CST present?")

def axiom_for(name):
    """the AXIOMS.md row whose statement names this condition (its stem before -paccayo)"""
    stem = name.replace("paccayo", "")
    for line in open(os.path.join(REPO, "kala", "AXIOMS.md"), encoding="utf-8"):
        m = re.match(r"\|\s*(A\d+)\s*\|([^|]*)\|", line)
        # the row names the condition in italics (*purejāta*) or leads with it ("Kamma: …", "Jhāna: …")
        if m and (re.search(rf"\*{re.escape(stem)}\*", m.group(2), re.I) or re.match(rf"\s*{re.escape(stem)}\s*:", m.group(2), re.I)):
            return m.group(1)
    return "—"

def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def build():
    items, (conds, cline) = matika(), conditions()
    upstream = open(os.path.join(CST, "UPSTREAM.txt")).readline().strip() if os.path.exists(os.path.join(CST, "UPSTREAM.txt")) else "unknown"
    tikas = [x for x in items if len(x["members"]) == 3]
    adukas = [x for x in items if len(x["members"]) == 2 and x["num"] <= 100]
    sdukas = [x for x in items if len(x["members"]) == 2 and x["num"] > 100]
    md = ["# MĀTIKĀ — the Dhammasaṅgaṇī's matrix and the Paṭṭhāna's 24 conditions, as generated data", "",
          "*GENERATED by `scripts/matika.py` from the local Chaṭṭha Saṅgāyana text — never edit by hand. Romanized canonical",
          "TERMS only (no running text: PREREGISTRATION-2026-09-27b.md §5); the edition's variant readings are dropped.*",
          f"*Text: {upstream}.*", "",
          f"**{len(tikas)} triads · {len(adukas)} Abhidhamma dyads · {len(sdukas)} Suttanta dyads · {len(conds)} conditions.** "
          "The Atthasālinī states 22 · 100 · 42 (`abh01a.att.xml:305`); `Matika.lean` checks the generated lists against them.", "",
          "## The triads and dyads", "", "| # | Group | Members (CST line) |", "|---|---|---|"]
    for x in items:
        md.append(f"| {x['num']} | {x['section']} | " + " · ".join(f"{t} (`abh01m.mul.xml:{n}`)" for t, n in x["members"]) + " |")
    md += ["", f"## The 24 conditions — the Paṭṭhāna's uddesa, `abh03m7.mul.xml:{cline}`", "",
           "| # | Condition | Its definition in AXIOMS.md |", "|---|---|---|"]
    for i, c in enumerate(conds, 1):
        md.append(f"| {i} | {c} | {axiom_for(c)} |")
    lean = ["/-", "  Matika.lean — GENERATED by scripts/matika.py from the local CST text; never edit by hand (capture step 2,",
            "  2026-10-13). The data, then the checks against the texts' own counts, then the Paṭṭhāna's method generator.", "-/",
            "namespace FormalAbhidhamma.Matika", "",
            "/-- A heading of the matrix: its number, its group, its members (romanized terms). -/",
            "structure Heading where", "  num : Nat", "  group : String", "  members : List String", "deriving Repr", ""]
    def emit(name, xs):
        lean.append(f"def {name} : List Heading := [")
        lean.append(",\n".join(f"  ⟨{x['num']}, {lean_str(x['section'] or '')}, [{', '.join(lean_str(t) for t, _ in x['members'])}]⟩" for x in xs))
        lean.append("]"); lean.append("")
    emit("tikas", tikas); emit("abhidhammaDukas", adukas); emit("suttantaDukas", sdukas)
    lean.append("/-- The 24 conditions, in the Paṭṭhāna's own order (its uddesa). -/")
    lean.append("def conditions : List String := [" + ", ".join(lean_str(c) for c in conds) + "]"); lean.append("")
    lean += [
        "/-! ## Checks against the texts' OWN counts (kala/ANSWERS.md) -/", "",
        "/-- The Atthasālinī (`abh01a.att.xml:305`): *dvāvīsati tikā*. -/",
        "theorem twentytwo_triads : tikas.length = 22 := by decide",
        "theorem every_triad_has_three : tikas.all (·.members.length = 3) = true := by decide",
        "/-- *ime sataṃ dukā*. -/",
        "theorem hundred_dyads : abhidhammaDukas.length = 100 := by decide",
        "theorem every_dyad_has_two : (abhidhammaDukas ++ suttantaDukas).all (·.members.length = 2) = true := by decide",
        "/-- *dvācattālīsa suttantikadukā*. -/",
        "theorem fortytwo_suttanta_dyads : suttantaDukas.length = 42 := by decide",
        "/-- The numbering runs unbroken: triads 1–22, Abhidhamma dyads 1–100, Suttanta dyads 101–142. -/",
        "theorem numbered_in_order : tikas.map (·.num) = (List.range 22).map (· + 1) ∧",
        "    abhidhammaDukas.map (·.num) = (List.range 100).map (· + 1) ∧",
        "    suttantaDukas.map (·.num) = (List.range 42).map (· + 101) := by decide",
        "/-- The Paṭṭhāna's uddesa names twenty-four conditions. -/",
        "theorem twentyfour_conditions : conditions.length = 24 := by decide", "",
        "/-! ## The Paṭṭhāna's method generator (structure, not text)",
        "  Six methods over the matrix (`abh03m7.mul.xml:449`, *cha anulomamhi nayā*; the Atthasālinī `abh01a.att.xml:313`),",
        "  in each of four directions (Paṭṭhāna-a `abh03a.att.xml:7665`: *samantā cha cha hutvā catuvīsati honti*). -/", "",
        "inductive Method | tika | duka | dukatika | tikaduka | tikatika | dukaduka",
        "  deriving DecidableEq, Repr", "",
        "inductive Direction | anuloma | paccaniya | anulomaPaccaniya | paccaniyanuloma",
        "  deriving DecidableEq, Repr", "",
        "def methods : List Method := [.tika, .duka, .dukatika, .tikaduka, .tikatika, .dukaduka]",
        "def directions : List Direction := [.anuloma, .paccaniya, .anulomaPaccaniya, .paccaniyanuloma]", "",
        "/-- The *samantapaṭṭhāna*: every method in every direction. -/",
        "def samantapatthana : List (Method × Direction) := methods.flatMap fun m => directions.map fun d => (m, d)", "",
        "/-- The commentary's count, reproduced from the generator: *catuvīsati samantapaṭṭhānāni*. -/",
        "theorem twentyfour_samantapatthana : samantapatthana.length = 24 := by decide", "",
        "/-- What a method ranges over, generated from the matrix: a triad, a dyad, or a dyad put into a triad and the converse",
        "    (*dvāvīsati tike gahetvā dukasate pakkhipitvā*). The two same-kind pairings (tikatika, dukaduka) are left unsized:",
        "    whether a heading pairs with itself, and whether order matters, the texts here do not say. -/",
        "def span : Method → Option Nat",
        "  | .tika => some tikas.length",
        "  | .duka => some abhidhammaDukas.length",
        "  | .dukatika => some (abhidhammaDukas.length * tikas.length)",
        "  | .tikaduka => some (tikas.length * abhidhammaDukas.length)",
        "  | .tikatika => none",
        "  | .dukaduka => none", "",
        "/-- Derived, NOT stated in the texts: putting the 22 triads into the 100 dyads gives 2,200 pairings each way. -/",
        "theorem cross_pairings : span .dukatika = some 2200 ∧ span .tikaduka = some 2200 := by decide", "",
        "end FormalAbhidhamma.Matika", ""]
    return "\n".join(md) + "\n", "\n".join(lean)

if __name__ == "__main__":
    md, lean = build()
    if "--check" in sys.argv:
        stale = [p for p, t in ((OUT_MD, md), (OUT_LEAN, lean)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        if stale: print("STALE:", ", ".join(os.path.relpath(p, REPO) for p in stale)); sys.exit(1)
        print("matika/ is current"); sys.exit(0)
    os.makedirs(os.path.dirname(OUT_MD), exist_ok=True)
    open(OUT_MD, "w", encoding="utf-8").write(md); open(OUT_LEAN, "w", encoding="utf-8").write(lean)
    print(md.split("\n")[6])
