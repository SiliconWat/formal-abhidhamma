def build():
    ds = defs()
    lines = [f"  {name} {ap} ∧   -- {f}" for f, name, ap in ds]
    lines[-1] = lines[-1].replace(" ∧   --", "     --")
    return HEAD + "\n".join(lines) + f"\n\n/-- How many definitions `Satisfies` conjoins. -/\ndef satisfiesCount : Nat := {len(ds)}\n\nend FormalAbhidhamma.Model\n"

if __name__ == "__main__":
    t = build()
    if sys.argv[1:] == ["--check"]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("World.lean is current" if cur == t else "World.lean is STALE — run model/world.py and commit"); sys.exit(0 if cur == t else 1)
    open(OUT, "w", encoding="utf-8").write(t); print("wrote", OUT, "-", t.count("\n"), "lines")
