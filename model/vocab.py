#!/usr/bin/env python3
"""vocab.py — the VOCABULARY of the encoding, and nothing else: every `inductive` and `structure` of the model's files (the 52 cetasikas, the citta's axes, the 28 kinds of matter, a stream, the matter placed in it, the one World …),
flattened into one namespace, with no row's definition, no table, no comment. It is what a second, BLIND encoder is given (Protocol 1 amendment 1, R2): enough to write a row in Lean over the same types, nothing of how it was written here.
  vocab.py          write model/Vocab.lean        vocab.py --check   exit 1 if stale"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
OUT = os.path.join(HERE, "Vocab.lean")
FILES = [("control/Cetasika.lean", None), ("sangaha/Citta.lean", None), ("matika/Relata.lean", {"Condition", "Kind"}),
         ("model/Mind.lean", None), ("model/Tax.lean", None), ("model/Proc.lean", None), ("model/Mat.lean", None), ("model/Link.lean", None), ("model/Cond.lean", None),
         ("model/Clocks.lean", None), ("model/Join.lean", None), ("model/Cosmos.lean", None), ("model/Status.lean", None), ("model/World.lean", None)]
def strip(t):
    # keep docstrings (/-- ... -/): they are the field meanings; drop file headers (/- ... -/) and line comments
    t = re.sub(r"/-(?!-).*?-/", "", t, flags=re.S); t = re.sub(r"(?m)^\s*--.*\n", "", t)
    # field meanings only: drop row ids, citations and provenance from the docstrings
    def clean(m):
        d = m.group(0)
        d = re.sub(r"\s*\((?:A\d+[a-z]?(?:[, ]+(?:and )?A\d+[a-z]?)*|K)\)", "", d)
        d = re.sub(r"\b[Ff]rom the row's cited lines, Protocol 1 correction 2 §2: ", "", d)
        d = re.sub(r"\bA\d+[a-z]?(?:, A\d+[a-z]?)*(?:'s)?:? ?", "", d)
        return d
    return re.sub(r"/--.*?-/", clean, t, flags=re.S)
def blocks(t):
    out, cur = [], None
    for l in t.split("\n"):
        if re.match(r"^(inductive|structure) ", l):
            if cur: out.append("\n".join(cur))
            cur = [l]
        elif cur is not None and (l.startswith(" ") or l.startswith("\t") or l.startswith("|")): cur.append(l)
        elif cur is not None and l.strip() == "": 
            out.append("\n".join(cur)); cur = None
        elif cur is not None:
            out.append("\n".join(cur)); cur = None
    if cur: out.append("\n".join(cur))
    return out
def flat(s): return s.replace("FormalAbhidhamma.Model.", "").replace("FormalAbhidhamma.Relata.", "").replace("FormalAbhidhamma.", "")
def build():
    L = ["/-", "  Vocab.lean — GENERATED by model/vocab.py: the types of the encoding and nothing else (no definition of any row). The vocabulary a second, blind encoder writes in.", "-/", "namespace V", ""]
    for f, only in FILES:
        for b in blocks(strip(open(os.path.join(REPO, f), encoding="utf-8").read())):
            name = re.match(r"^(?:inductive|structure) (\w+)", b).group(1)
            if only is not None and name not in only: continue
            b = re.sub(r"\n{2,}", "\n", flat(b)).rstrip()
            L.append(b); L.append("")
    L.append("end V")
    return "\n".join(L) + "\n"
if __name__ == "__main__":
    t = build()
    if sys.argv[1:] == ["--check"]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("Vocab.lean is current" if cur == t else "Vocab.lean is STALE — run model/vocab.py and commit"); sys.exit(0 if cur == t else 1)
    open(OUT, "w", encoding="utf-8").write(t); print("wrote", OUT, len(t.splitlines()), "lines")
