#!/usr/bin/env python3
"""lists.py — generate model/LISTS.md: the OCCURRENCE LIST, the VARIANTS and the FREEDOMS that Protocol 1 §8 step 2 owes before the encoding is frozen.
Generated from CENSUS.md (the 'Occurs' and 'Variant / freedom' columns of the row table) and from the encoding's own headers (every line that says
FREEDOM or PERMISSION), never typed by hand, so the lists cannot drift from the files.  `lists.py --check` exits 1 if LISTS.md is stale."""
import glob, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "LISTS.md")

def rows():
    out = []
    for line in open(os.path.join(HERE, "CENSUS.md"), encoding="utf-8"):
        m = re.match(r"\| (A\d+b?|C|K) \| ([^|]*)\| ([A-Z]) \| ([^|]*)\| (.*?) \| ([^|]*) \| ([^|]*) \|\s*$", line)
        if m: out.append(dict(id=m.group(1), cls=m.group(3), part=m.group(4).strip(), text=m.group(5).strip(), occurs=m.group(6).strip(), note=m.group(7).strip()))
    return out

def header_lines(word):
    """Lines of the model files' comments that carry a declared FREEDOM or PERMISSION."""
    res = []
    for f in sorted(glob.glob(os.path.join(HERE, "*.lean"))):
        for n, l in enumerate(open(f, encoding="utf-8"), 1):
            if re.search(word, l): res.append((os.path.basename(f), n, l.strip()))
    return res

def build():
    rs = rows()
    L = ["# LISTS — the occurrence list, the variants and the freedoms",
         "", "*GENERATED by `model/lists.py` from `CENSUS.md` and the encoding's own comments; ⛔ never edited by hand. Protocol 1 §8 step 2 owes them before the encoding is frozen;",
         "Protocol 2 registers them. A row's entry here is what the encoding does NOT forbid: a thing the world MUST contain, a rival reading tested in its own model, or a choice the texts leave open.*", ""]
    occ = [r for r in rs if r["occurs"] not in ("—", "", "-")]
    L += [f"## 1. The occurrence list — what a model must CONTAIN ({len(occ)} rows)", "",
          "| Row | Class | Part | Must occur |", "|---|---|---|---|"]
    L += [f"| {r['id']} | {r['cls']} | {r['part']} | {r['occurs']} |" for r in occ]
    L += ["", "### 1b. Permissions — clauses that PERMIT, with no forbidden world (they add to the occurrence list)", ""]
    for f, n, l in header_lines(r"PERMIT|permission"): L.append(f"- `{f}:{n}` {l}")
    var = [r for r in rs if r["note"] not in ("—", "", "-")]
    L += ["", f"## 2. The variants and noted readings ({len(var)} rows) — each rival reading is tested in its OWN model, never entered with its rival", "",
          "| Row | Class | Part | Note |", "|---|---|---|---|"]
    L += [f"| {r['id']} | {r['cls']} | {r['part']} | {r['note']} |" for r in var]
    L += ["", "## 3. The freedoms — what the World leaves open (a model that needs a freedom some live row closes does not count)", ""]
    fr = [r for r in rs if re.search(r"(?i)freedom", r["note"])]
    for r in fr: L.append(f"- **{r['id']}** — {r['note']}")
    L += ["", "### 3b. Declared in the encoding's own comments", ""]
    for f, n, l in header_lines(r"FREEDOM|freedoms? list|Declared freedom"): L.append(f"- `{f}:{n}` {l}")
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    text = build()
    if sys.argv[1:] == ["--check"]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("LISTS.md is current" if cur == text else "LISTS.md is STALE — run model/lists.py and commit"); sys.exit(0 if cur == text else 1)
    open(OUT, "w", encoding="utf-8").write(text); print("wrote", OUT, f"({len(text.splitlines())} lines)")
