#!/usr/bin/env python3
"""table.py — build model/TABLE.md, the table the founder reads before Protocol 2 (Protocol 1 §8 step 3): for every row of the axiom list the encoding touches, the row's own words
(kala/AXIOMS.md), then each definition that encodes it as Lean (from the comment-stripped copy) beside the BLIND reader's plain English (model/BLIND.md).
A definition is filed under the row its name begins with (a38_… → A38, c_… → C, k_… → K). GENERATED; ⛔ never edited by hand.   table.py --check exits 1 if stale."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
OUT = os.path.join(HERE, "TABLE.md")

def rows():
    d = {}
    for l in open(os.path.join(REPO, "kala", "AXIOMS.md"), encoding="utf-8"):
        m = re.match(r"\|\s*(A\d+b?|C|K|A0′?)\s*\|(.*)", l)
        if m: d[m.group(1)] = m.group(2).split("|")[0].strip()
    return d

def blind_english():
    d = {}
    for l in open(os.path.join(HERE, "BLIND.md"), encoding="utf-8"):
        m = re.match(r"\| ([^|]+?) \| (.*) \|\s*$", l)
        if m and not m.group(1).startswith("definition") and not m.group(1).startswith("---"):
            for name in re.split(r" / ", m.group(1)): d[name.strip()] = m.group(2).strip()
    return d

def lean_defs():
    d = {}
    for f in sorted(os.listdir(os.path.join(HERE, "blind"))):
        t = open(os.path.join(HERE, "blind", f), encoding="utf-8").read()
        for m in re.finditer(r"(?ms)^def (\w+)\b.*?(?=^\S|\Z)", t):
            d[m.group(1)] = (f, m.group(0).rstrip())
    return d

def row_of(name):
    m = re.match(r"(a\d+b?)_", name)
    if m: return m.group(1).upper()
    if name.startswith("c_"): return "C"
    if name.startswith("k_"): return "K"
    return None

def build():
    R, B, D = rows(), blind_english(), lean_defs()
    by = {}
    for name, (f, src) in D.items():
        r = row_of(name)
        if r: by.setdefault(r, []).append((name, f, src))
    key = lambda r: (0, int(re.sub(r"\D", "", r) or 0), r) if r.startswith("A") else (1, 0, r)
    L = ["# TABLE — every row beside its Lean and the blind reader's plain English", "",
         "*GENERATED by `model/table.py` from `kala/AXIOMS.md`, `model/blind/` (the comment-stripped Lean) and `model/BLIND.md` (the readers' plain English). Protocol 1 §8 step 3: the founder reads this before Protocol 2;",
         "a mismatch between a row and its reading is fixed in the definition, never explained away. ⛔ Never edited by hand.*", "",
         f"**{len(by)} rows have at least one definition; {sum(len(v) for v in by.values())} definitions; {sum(1 for v in by.values() for n, _, _ in v if n in B)} have a blind reading.**", ""]
    for r in sorted(by, key=key):
        text = R.get(r, "(row not found in AXIOMS.md)")
        L += [f"## {r}", "", "> " + (text if len(text) < 700 else text[:700] + " …"), ""]
        for name, f, src in sorted(by[r]):
            eng = B.get(name, "*(no blind reading recorded)*")
            L += [f"**`{name}`** ({f})", "", "```lean", src, "```", "", f"*Blind reader:* {eng}", ""]
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    t = build()
    if sys.argv[1:] == ["--check"]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("TABLE.md is current" if cur == t else "TABLE.md is STALE — run model/table.py and commit"); sys.exit(0 if cur == t else 1)
    open(OUT, "w", encoding="utf-8").write(t)
    print("wrote", OUT, len(t.splitlines()), "lines;", t.split("\n")[6])
